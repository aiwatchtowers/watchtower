package relay

import (
	"bytes"
	"crypto/ed25519"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"os"
	"path/filepath"
	"testing"

	"watchtower/internal/hub/transport/relay/client"
)

// updateKitVectors rewrites the Kit's relay auth vectors instead of comparing
// with them: go test ./internal/hub/transport/relay -run TestKitRelayAuthVectors -update
var updateKitVectors = flag.Bool("update", false, "rewrite WatchtowerKit/Tests/Fixtures/relay/auth_vectors.json")

// kitAuthVectorsPath is the fixture the Kit's RelayAuthVectorTests read.
var kitAuthVectorsPath = filepath.Join("..", "..", "..", "..", "WatchtowerKit", "Tests", "Fixtures", "relay", "auth_vectors.json")

// kitAuthVector is one case of the fixture; every byte field is lower-case hex.
type kitAuthVector struct {
	Seed                   string `json:"seed"`
	AuthPub                string `json:"auth_pub"`
	RelayDeviceID          string `json:"relay_device_id"`
	Nonce                  string `json:"nonce"`
	Origin                 string `json:"origin"`
	RegisterClientDataHash string `json:"register_client_data_hash"`
	RegisterSignature      string `json:"register_signature"`
	LoginMessage           string `json:"login_message"`
	LoginSignature         string `json:"login_signature"`
	LoginClientDataHash    string `json:"login_client_data_hash"`
}

type kitAuthVectors struct {
	Comment string          `json:"comment"`
	Cases   []kitAuthVector `json:"cases"`
}

// buildKitAuthVector computes a case the way the Go client does: the device id
// and the register hash from the client package, the login message as
// loginLocked builds it, the login hash per the relay's proto/README.md.
// ed25519.Sign is deterministic, so the signatures are stable bytes.
func buildKitAuthVector(t *testing.T, seedHex, nonceHex, origin string) kitAuthVector {
	t.Helper()
	seed, err := hex.DecodeString(seedHex)
	if err != nil || len(seed) != ed25519.SeedSize {
		t.Fatalf("bad seed %q: %v", seedHex, err)
	}
	nonce, err := hex.DecodeString(nonceHex)
	if err != nil {
		t.Fatalf("bad nonce %q: %v", nonceHex, err)
	}
	key := ed25519.NewKeyFromSeed(seed)
	pub := key.Public().(ed25519.PublicKey)
	id := client.DeviceID(pub)
	regHash := client.RegisterClientDataHash(nonce, pub, origin)

	// The login message mirrors client.loginLocked (nonce || device id ||
	// origin), which keeps it inline; the login clientDataHash is the App
	// Attest input from the relay's proto/README.md, which the Go client
	// does not compute. Keep both in step with those sources.
	loginMsg := make([]byte, 0, len(nonce)+len(id)+len(origin))
	loginMsg = append(append(append(loginMsg, nonce...), id...), origin...)

	h := sha256.New()
	h.Write([]byte("relay/v1/login"))
	h.Write(nonce)
	h.Write([]byte(id))
	h.Write([]byte(origin))

	return kitAuthVector{
		Seed:                   seedHex,
		AuthPub:                hex.EncodeToString(pub),
		RelayDeviceID:          id,
		Nonce:                  nonceHex,
		Origin:                 origin,
		RegisterClientDataHash: hex.EncodeToString(regHash),
		RegisterSignature:      hex.EncodeToString(ed25519.Sign(key, regHash)),
		LoginMessage:           hex.EncodeToString(loginMsg),
		LoginSignature:         hex.EncodeToString(ed25519.Sign(key, loginMsg)),
		LoginClientDataHash:    hex.EncodeToString(h.Sum(nil)),
	}
}

// TestKitRelayAuthVectors pins the Swift relay client's device id and its
// register/login messages to the Go client: the Kit's RelayAuthVectorTests
// read the same file, and this test fails when the Go side changes without the
// fixture being regenerated.
func TestKitRelayAuthVectors(t *testing.T) {
	want := kitAuthVectors{
		Comment: "Generated by TestKitRelayAuthVectors (internal/hub/transport/relay/kitvectors_test.go); regenerate with -update. Fixed test seeds only.",
		Cases: []kitAuthVector{
			buildKitAuthVector(t,
				"000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f",
				"a0a1a2a3a4a5a6a7a8a9aaabacadaeafb0b1b2b3b4b5b6b7b8b9babbbcbdbebf",
				"https://relay.example.com"),
			buildKitAuthVector(t,
				"5f5e5d5c5b5a595857565554535251504f4e4d4c4b4a49484746454443424140",
				"0f1e2d3c4b5a69788796a5b4c3d2e1f00112233445566778899aabbccddeeff0",
				"http://127.0.0.1:8787"),
		},
	}
	encoded, err := json.MarshalIndent(want, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	encoded = append(encoded, '\n')

	if *updateKitVectors {
		if err := os.MkdirAll(filepath.Dir(kitAuthVectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(kitAuthVectorsPath, encoded, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(kitAuthVectorsPath)
	if err != nil {
		t.Fatalf("read %s (regenerate with -update): %v", kitAuthVectorsPath, err)
	}
	if !bytes.Equal(got, encoded) {
		t.Fatalf("%s is stale: regenerate with go test ./internal/hub/transport/relay -run TestKitRelayAuthVectors -update", kitAuthVectorsPath)
	}
}
