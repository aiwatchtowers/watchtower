// switch, on purpose. reason is mandatory (checked at the top of the test) —
// an entry with no reason is exactly the "next person silences the scan by
// appending a bare line" failure mode this shape exists to prevent.
type allowedStrongSource struct {
	tag    string
	reason string
}

